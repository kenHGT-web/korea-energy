const pairs={en:entries.map(([ru,en])=>[ru,en]),ko:entries.map(([ru,en,ko])=>[ru,ko])};
for(const lang of ['en','ko']) pairs[lang].sort((a,b)=>b[0].length-a[0].length);
const original=new WeakMap();const rendered=new WeakMap();
function translateText(raw,lang){let out=raw;for(const [a,b] of pairs[lang]){if(out.includes(a))out=out.split(a).join(b)}return out}
function localizeNode(node,lang){
 if(node.nodeType===3){const now=node.nodeValue;const prev=rendered.get(node);if(prev!==now){original.set(node,now)}const source=original.get(node)??now;const next=lang==='ru'?source:translateText(source,lang);rendered.set(node,next);if(now!==next)node.nodeValue=next;return}
 if(node.nodeType!==1)return;
 if(node.matches('script,style,textarea,input,option'))return;
 for(const attr of ['aria-label','title','placeholder']){if(node.hasAttribute(attr)){const key=attr+':origin',last=attr+':last';let saved=node[key];const now=node.getAttribute(attr);if(saved===undefined||node[last]!==now){saved=now;node[key]=saved}const next=lang==='ru'?saved:translateText(saved,lang);node[last]=next;if(now!==next)node.setAttribute(attr,next)}}
 for(const child of node.childNodes)localizeNode(child,lang)
}
export function installArcadeI18n(overlay){
 const lang=()=>['ru','en','ko'].includes(document.documentElement.lang)?document.documentElement.lang:'ru';
 let running=false;
 function update(){if(running)return;running=true;try{localizeNode(overlay,lang())}finally{running=false}}
 const observer=new MutationObserver(update);observer.observe(overlay,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['aria-label','title','placeholder']});
 const langs=new MutationObserver(update);langs.observe(document.documentElement,{attributes:true,attributeFilter:['lang']});update();
 return()=>{observer.disconnect();langs.disconnect()}
}
